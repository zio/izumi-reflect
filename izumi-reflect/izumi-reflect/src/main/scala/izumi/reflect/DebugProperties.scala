package izumi.reflect

/**
  * The names of the system properties and of the macro setting that control the debug output, assertions, caches and
  * equality shortcut of `izumi-reflect`. Each field holds its own name, so code can refer to a setting without typing
  * the string.
  *
  * {{{
  * val debugFlag: String = DebugProperties.`izumi.reflect.debug.macro.rtti` // "izumi.reflect.debug.macro.rtti"
  * }}}
  *
  * @see [[https://zio.dev/izumi-reflect/reference/debugging/ Debugging and DebugProperties]]
  */
object DebugProperties {
  /**
    * Set system property `-Dizumi.reflect.rtti.optimized.equals=false` to disable the optimized `equals` comparison of
    * [[izumi.reflect.macrortti.LightTypeTag]]s created at compile time or read with `LightTypeTag.parse`: by default,
    * two such tags with the current format version and different serialized strings are not equal, without a comparison
    * of their structure. Try this if you're experiencing "impossible" false negatives. While we believe that such false
    * negatives are impossible, even between tags generated by different versions of `izumi-reflect`, they could still be
    * possible in actuality. The property is read once, in the JVM that runs the program.
    *
    * {{{
    * // no-check: shell command
    * sbt -Dizumi.reflect.rtti.optimized.equals=false
    * }}}
    *
    * Default: `true`
    */
  final val `izumi.reflect.rtti.optimized.equals` = "izumi.reflect.rtti.optimized.equals"

  /**
    * Add compiler option `-Xmacro-settings:izumi.reflect.rtti.cache.compile=false` to disable compile-time caching of computed
    * LightTypeTags. Caching is enabled by default for compile-time light type tag creation. Only the Scala 2 macros
    * read this setting.
    *
    * {{{
    * // no-check: sbt setting
    * scalacOptions += "-Xmacro-settings:izumi.reflect.rtti.cache.compile=false"
    * }}}
    *
    * Default: `true`
    */
  final val `izumi.reflect.rtti.cache.compile` = "izumi.reflect.rtti.cache.compile"

  /**
    * Set system property `-Dizumi.reflect.rtti.cache.runtime=false` to disable caching for runtime creation of LightTypeTags.
    * Caching is enabled by default for runtime light type tag creation. Runtime creation means
    * `LightTypeTagImpl.makeLightTypeTag`, which builds tags from `scala-reflect` types on Scala 2.
    *
    * {{{
    * // no-check: shell command
    * sbt -Dizumi.reflect.rtti.cache.runtime=false
    * }}}
    *
    * Default: `true`
    */
  final val `izumi.reflect.rtti.cache.runtime` = "izumi.reflect.rtti.cache.runtime"

  /**
    * Set system property `-Dizumi.reflect.debug.macro.rtti=true` to see debug output. In the JVM that runs the program,
    * it prints each step of `LightTypeTag#<:<` subtype checks. In the JVM that runs the compiler, it prints how the
    * Scala 2 macros build each tag; the Scala 3 macros have no debug output. A shorter prefix of the name set to `true`,
    * such as `-Dizumi.reflect=true`, also enables it.
    *
    * {{{
    * // no-check: shell command
    * sbt -Dizumi.reflect.debug.macro.rtti=true compile
    * }}}
    *
    * Default: `false`
    */
  final val `izumi.reflect.debug.macro.rtti` = "izumi.reflect.debug.macro.rtti"

  /**
    * To enable sanity checking assertions in the Scala 2 code that builds tags, set
    * `-Dizumi.reflect.debug.macro.rtti.assertions=true` system property. Set it in the JVM that runs the compiler to
    * check the tags built during compilation.
    *
    * {{{
    * // no-check: shell command
    * sbt -Dizumi.reflect.debug.macro.rtti.assertions=true compile
    * }}}
    *
    * Default: `false`
    */
  final val `izumi.reflect.debug.macro.rtti.assertions` = "izumi.reflect.debug.macro.rtti.assertions"

}
